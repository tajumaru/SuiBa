export const timeText = (at: number) =>
  new Intl.DateTimeFormat("ja-JP", {
    timeZone: "Asia/Tokyo",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hour12: false,
  }).format(new Date(at));

/**
 * The agent narration feed, shown on its own tab (the default view
 * after login). A white dome character (five fixed poses) narrates the bot's
 * activity in a chat-style timeline. Every entry is generated by the
 * pure functions in agentNarration.ts from the worker's real records
 * (operation events, candidate audits, decision evidence) — the
 * component itself invents nothing, and when the display goes stale
 * the feed stops advancing, just like the vital signs.
 *
 * The character itself no longer lives in this panel: it rides
 * at the top of the app as a round avatar (AgentHeaderAvatar) on
 * every tab, staying in view while the page scrolls, and this
 * feed — the one place that advances the narration
 * state — reports each derived pose through onPoseChange so the
 * avatar and the narration can never disagree. The artwork is
 * AI-generated raster imagery; the pose is a symbol of the recorded
 * state, not a measurement, and decoration on the same recorded
 * state, never a signal of its own.
 *
 * Under the condition chips, the "いまの注目" strip shows the one
 * entry condition the narration has declared it is watching (the
 * watched chip carries a ● marker): its current recorded value and
 * how it has moved since the declaration — or, when there is no
 * watch, why not. Like the chips, it derives only from the fresh
 * decision evidence via currentWatch and vanishes when stale.
 *
 * Under the watch strip, a quiet score strip keeps the session's
 * declaration record （宣言/進行中/的中/外れ — total, the live one,
 * then the settled results), and at a milestone the feed itself pauses for a
 * ふりかえり entry (purple border, tagged) built from that same
 * record — both come from agentNarration.ts, never from the
 * component.
 *
 * A sudden market move breaks in as a 速報 entry (orange-red
 * border, tagged): agentNarration.ts detects it from the recorded
 * decision prices and volume change, with a warm-up and a cooldown
 * so it cannot chatter. The component only renders the tag.
 *
 * A recorded buy fill wears a gold frame and a 「買えた！」 tag for
 * good. When one lands as genuinely new this session — an advance
 * after the initialising one adds a fresh buy entry — the feed
 * also reports a celebration through onCelebrate and pulses the
 * new entry once; the loaded history and sell fills never do.
 */
/**
 * One feed entry row. A recorded buy fill is marked for good —
 * gold frame and a 「買えた！」 tag — so a buy stays recognisable
 * in the history, while a sell fill keeps the plain trade look.
 * `justBought` adds the one-shot pulse class for the entry whose
 * arrival just opened a celebration (the pulse itself is defined
 * only when motion is allowed, in style.css).
 */
export function AgentFeedEntryRow({
  entry,
  justBought = false,
  animateIn = false,
  onPromptChip,
  speakerName = "キャラ",
  memorySealed = false,
  onOpenMemorySeal,
  onReplay,
}: {
  entry: NarrationEntry;
  justBought?: boolean;
  /** Plays the one-shot entrance for an entry newly added to the live edge. */
  animateIn?: boolean;
  /** Tapping the suggested question on a chatPrompt entry asks it. */
  onPromptChip?: (chip: string) => void;
  /** The character's display name, for its speak-up tag. */
  speakerName?: string;
  /** Whether this newly arrived memory is still covered on this device. */
  memorySealed?: boolean;
  /** Records that the device-local memory seal has been opened. */
  onOpenMemorySeal?: (entryId: string) => void;
  /** Opens the saved highlight replay for this exact entry. */
  onReplay?: () => void;
}) {
  const buy = isBuyTradeEntry(entry);
  const shield = entry.kind === "rejection" && entry.skill === "shield";
  const forecastSkill =
    entry.kind === "forecastCall" || entry.kind === "forecastHit" || entry.kind === "forecastCalib";
  return (
    <div
      className={`agent-feed-entry ${entry.kind}${shield || entry.kind === "levelUp" ? " rpg-gold" : ""}${entry.kind === "sellLineCrossing" ? ` crossing-${entry.sellLineSide}` : ""}${buy ? " buy" : ""}${justBought ? " just-bought" : ""}${animateIn ? " animate-in" : ""}${entry.mono ? " mono" : ""}${entry.kind === "memory" && memorySealed ? " sealed-memory" : ""}`}
    >
      {entry.kind === "memory" && (
        <img
          className="agent-feed-memory-bg"
          src="/walrus-memory-bg.png"
          alt=""
          aria-hidden="true"
        />
      )}
      {entry.kind === "memory" && memorySealed && onOpenMemorySeal && (
        <MemoryKeySeal
          entryId={entry.id}
          onOpen={() => onOpenMemorySeal(entry.id)}
        />
      )}
      <time dateTime={new Date(entry.at).toISOString()}>
        {timeText(entry.at)}
      </time>
      {shield && <span className="agent-feed-entry-tag rpg-gold">スキル発動 まもりの盾</span>}
      {entry.kind === "levelUp" && (
        <span className="agent-feed-entry-tag rpg-gold">レベルアップ</span>
      )}
      {forecastSkill && <span className="agent-feed-entry-tag rpg-forecast">さきよみ</span>}
      {entry.kind === "greeting" && (
        <span className="agent-feed-entry-tag">交代</span>
      )}
      {entry.kind === "review" && (
        <span className="agent-feed-entry-tag">ふりかえり</span>
      )}
      {entry.kind === "alert" && (
        <span className="agent-feed-entry-tag alert">速報</span>
      )}
      {entry.kind === "nearMiss" && (
        <span className="agent-feed-entry-tag nearmiss">ニアミス</span>
      )}
      {entry.kind === "watchHit" && (
        <span className="agent-feed-entry-tag hit">的中</span>
      )}
      {entry.kind === "reach" && (
        <span className="agent-feed-entry-tag reach">リーチ</span>
      )}
      {entry.kind === "superReach" && (
        <span className="agent-feed-entry-tag super-reach">スーパーリーチ</span>
      )}
      {entry.kind === "sleepTalk" && (
        <span className="agent-feed-entry-tag sleep">寝言</span>
      )}
      {entry.kind === "epoch" && (
        <span className="agent-feed-entry-tag epoch">チェーン</span>
      )}
      {entry.kind === "monthlyReport" && (
        <span className="agent-feed-entry-tag monthly">月報</span>
      )}
      {entry.kind === "btc" && (
        <span className="agent-feed-entry-tag btc">BTC</span>
      )}
      {entry.kind === "bookWall" && (
        <span className="agent-feed-entry-tag book">板</span>
      )}
      {entry.kind === "forecastCall" && (
        <span className="agent-feed-entry-tag forecast">予測</span>
      )}
      {entry.kind === "forecastHit" && (
        <span className="agent-feed-entry-tag hit">予測的中</span>
      )}
      {entry.kind === "forecastMiss" && (
        <span className="agent-feed-entry-tag forecast-miss">予測外れ</span>
      )}
      {entry.kind === "forecastTouch" && (
        <span className="agent-feed-entry-tag touch">タッチ</span>
      )}
      {entry.kind === "forecastTouchNear" && (
        <span className="agent-feed-entry-tag touch-near">タッチならず</span>
      )}
      {entry.kind === "forecastCalib" && (
        <span className="agent-feed-entry-tag calib">学習</span>
      )}
      {entry.kind === "memory" && (
        <span className="agent-feed-entry-tag">記憶</span>
      )}
      {entry.kind === "priceLine" && (
        <span className="agent-feed-entry-tag line">買い走りライン</span>
      )}
      {entry.kind === "priceLineReached" && (
        <span className="agent-feed-entry-tag reached">到達</span>
      )}
      {entry.kind === "sellLine" && (
        <span className="agent-feed-entry-tag sell">売りライン</span>
      )}
      {entry.kind === "sellLineCrossing" && (
        <span className={`agent-feed-entry-tag crossing-${entry.sellLineSide}`}>
          {entry.sellLineSide === "sl" ? "損切り接近" : "利確接近"}
        </span>
      )}
      {entry.kind === "chatUser" && (
        <span className="agent-feed-entry-tag user">あなた</span>
      )}
      {entry.kind === "chatReply" && (
        <span className="agent-feed-entry-tag reply">
          {entry.mono ? "CMD" : "返信"}
        </span>
      )}
      {entry.kind === "chatPrompt" && (
        <span className="agent-feed-entry-tag reply">{speakerName}</span>
      )}
      {buy && <span className="agent-feed-entry-tag buy">買えた！</span>}
      <p>{entry.text}</p>
      {entry.kind === "chatPrompt" && entry.promptChip && onPromptChip && (
        <button
          type="button"
          className="agent-feed-prompt-chip"
          onClick={() => onPromptChip(entry.promptChip!)}
        >
          {entry.promptChip}
        </button>
      )}
      {onReplay && (
        <button
          type="button"
          className="agent-feed-replay-button"
          onClick={onReplay}
        >
          再演
        </button>
      )}
    </div>
  );
}

const TAP_MS = 260;
const TAP_DISTANCE = 10;
const OPEN_FRACTION = 0.3;
const FADE_MS = 220;

function MemoryKeySeal({
  entryId,
  onOpen,
}: {
  entryId: string;
  onOpen: () => void;
}) {
  const canvasRef = useRef<HTMLCanvasElement>(null);
  const pointerRef = useRef<{
    id: number;
    x: number;
    y: number;
    startedAt: number;
    distance: number;
  } | null>(null);
  const openedRef = useRef(false);
  const openTimerRef = useRef<number | null>(null);
  const [opening, setOpening] = useState(false);
  const reducedMotion = usePrefersReducedMotion();

  const open = useCallback(() => {
    if (openedRef.current) return;
    openedRef.current = true;
    if (reducedMotion) {
      onOpen();
      return;
    }
    setOpening(true);
    openTimerRef.current = window.setTimeout(onOpen, FADE_MS);
  }, [onOpen, reducedMotion]);

  useEffect(
    () => () => {
      if (openTimerRef.current != null)
        window.clearTimeout(openTimerRef.current);
    },
    [],
  );

  const drawCover = useCallback(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const rect = canvas.getBoundingClientRect();
    if (rect.width <= 0 || rect.height <= 0) return;
    const ratio = Math.max(1, window.devicePixelRatio || 1);
    canvas.width = Math.round(rect.width * ratio);
    canvas.height = Math.round(rect.height * ratio);
    const ctx = canvas.getContext("2d");
    if (!ctx) return;
    ctx.scale(ratio, ratio);
    const style = getComputedStyle(canvas);
    const mint = style.getPropertyValue("--mint").trim();
    const pine = style.getPropertyValue("--pine").trim();
    ctx.globalCompositeOperation = "source-over";
    ctx.fillStyle = pine;
    ctx.fillRect(0, 0, rect.width, rect.height);

    const centerX = rect.width / 2;
    const motifY = Math.max(34, rect.height / 2 - 17);
    ctx.strokeStyle = mint;
    ctx.fillStyle = mint;
    ctx.lineWidth = 3;
    ctx.beginPath();
    ctx.arc(centerX, motifY, 22, 0, Math.PI * 2);
    ctx.stroke();
    ctx.beginPath();
    ctx.arc(centerX, motifY - 4, 6, 0, Math.PI * 2);
    ctx.fill();
    ctx.beginPath();
    ctx.moveTo(centerX - 7, motifY + 1);
    ctx.lineTo(centerX + 7, motifY + 1);
    ctx.lineTo(centerX + 11, motifY + 16);
    ctx.lineTo(centerX - 11, motifY + 16);
    ctx.closePath();
    ctx.fill();

    ctx.textAlign = "center";
    ctx.textBaseline = "middle";
    ctx.font = `600 14px ${style.fontFamily}`;
    ctx.fillText("鍵のかかった記憶", centerX, motifY + 42);
    ctx.font = `12px ${style.fontFamily}`;
    ctx.fillText("なぞって鍵を開ける", centerX, motifY + 62);
  }, []);

  useEffect(() => {
    drawCover();
    const canvas = canvasRef.current;
    if (!canvas) return;
    const observer = new ResizeObserver(drawCover);
    observer.observe(canvas);
    return () => observer.disconnect();
  }, [drawCover]);

  const point = (event: React.PointerEvent<HTMLCanvasElement>) => {
    const canvas = event.currentTarget;
    const rect = canvas.getBoundingClientRect();
    return {
      x: event.clientX - rect.left,
      y: event.clientY - rect.top,
    };
  };

  const erasedFraction = (canvas: HTMLCanvasElement) => {
    const ctx = canvas.getContext("2d");
    if (!ctx) return 0;
    const step = 8;
    const pixels = ctx.getImageData(0, 0, canvas.width, canvas.height).data;
    let erased = 0;
    let sampled = 0;
    for (let y = 0; y < canvas.height; y += step) {
      for (let x = 0; x < canvas.width; x += step) {
        sampled += 1;
        if (pixels[(y * canvas.width + x) * 4 + 3] < 128) erased += 1;
      }
    }
    return erased / sampled;
  };

  return (
    <canvas
      ref={canvasRef}
      className={`agent-feed-memory-seal${opening ? " opening" : ""}`}
      aria-label="鍵のかかった記憶。なぞるか、短く押して開く"
      role="button"
      tabIndex={0}
      data-memory-seal={entryId}
      onKeyDown={(event) => {
        if (event.key === "Enter" || event.key === " ") {
          event.preventDefault();
          open();
        }
      }}
      onPointerDown={(event) => {
        const p = point(event);
        event.currentTarget.setPointerCapture(event.pointerId);
        pointerRef.current = {
          id: event.pointerId,
          ...p,
          startedAt: performance.now(),
          distance: 0,
        };
      }}
      onPointerMove={(event) => {
        const previous = pointerRef.current;
        if (!previous || previous.id !== event.pointerId) return;
        const p = point(event);
        const ctx = event.currentTarget.getContext("2d");
        if (!ctx) return;
        ctx.globalCompositeOperation = "destination-out";
        ctx.lineCap = "round";
        ctx.lineJoin = "round";
        ctx.lineWidth = Math.max(34, event.currentTarget.clientHeight * 0.2);
        ctx.beginPath();
        ctx.moveTo(previous.x, previous.y);
        ctx.lineTo(p.x, p.y);
        ctx.stroke();
        previous.distance += Math.hypot(p.x - previous.x, p.y - previous.y);
        previous.x = p.x;
        previous.y = p.y;
        if (erasedFraction(event.currentTarget) > OPEN_FRACTION) open();
      }}
      onPointerUp={(event) => {
        const pointer = pointerRef.current;
        pointerRef.current = null;
        if (
          pointer?.id === event.pointerId &&
          performance.now() - pointer.startedAt <= TAP_MS &&
          pointer.distance <= TAP_DISTANCE
        )
          open();
      }}
      onPointerCancel={() => {
        pointerRef.current = null;
      }}
    />
  );
}
