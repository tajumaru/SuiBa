const FALLBACK_LABELS = new Set([
  "価格見積もりの取得・検証に失敗しました",
  "市場データの取得・検証に失敗しました",
  "Sui読み取りAPIの接続確認に失敗しました",
  "安全条件またはデータの整合性を確認できません",
]);

describe("operationReason", () => {
  it.each([...new Set(OPERATION_EVENT_CODES)])(
    "resolves operation event code %s to a specific label",
    (code) => expect(FALLBACK_LABELS).not.toContain(operationReason(code)),
  );
});
